-- profiles：所有人可读公开字段，本人可改资料，角色/状态只能由管理员 RPC 修改
drop policy if exists profiles_select on public.profiles;
create policy profiles_select on public.profiles for select using (true);

drop policy if exists profiles_update_own on public.profiles;
create policy profiles_update_own on public.profiles for update
  using (id = auth.uid())
  with check (id = auth.uid());

revoke all on public.profiles from anon, authenticated;
grant select (id, username, nickname, avatar, role, status, register_time)
  on public.profiles to anon, authenticated;
grant update (nickname, avatar, phone, email)
  on public.profiles to authenticated;

-- categories：所有人可读，管理员可写
drop policy if exists categories_select on public.categories;
create policy categories_select on public.categories for select using (true);

drop policy if exists categories_write_admin on public.categories;
create policy categories_write_admin on public.categories for all
  using (public.is_admin()) with check (public.is_admin());

-- products：在售商品公开；本人/管理员/下单双方/收藏者可见；本人可增改；管理员可改
drop policy if exists products_select on public.products;
create policy products_select on public.products for select
  using (
    status = 1
    or user_id = auth.uid()
    or public.is_admin()
    -- 订单里的商品可能已预留/售出，买卖双方仍需看到名称和图片
    or exists (
      select 1 from public.orders o
      where o.product_id = products.id
        and (o.buyer_id = auth.uid() or o.seller_id = auth.uid())
    )
    -- 收藏列表里的商品可能已下架/售出
    or exists (
      select 1 from public.interactions i
      where i.product_id = products.id and i.user_id = auth.uid()
    )
  );

drop policy if exists products_insert_own on public.products;
create policy products_insert_own on public.products for insert
  with check (user_id = auth.uid() and status = 1);

drop policy if exists products_update_own on public.products;
create policy products_update_own on public.products for update
  -- 普通用户只能在 在售/下架 两个状态间切换，已预留/已售出由订单 RPC 管理
  using (
    public.is_admin()
    or (user_id = auth.uid() and status in (0, 1))
  )
  with check (
    public.is_admin()
    or (user_id = auth.uid() and status in (0, 1))
  );

revoke update on public.products from anon, authenticated;
grant update (product_name, product_image, price, description, category_id, item_condition, status)
  on public.products to authenticated;

drop policy if exists products_delete_own on public.products;
create policy products_delete_own on public.products for delete
  using (user_id = auth.uid() or public.is_admin());

-- addresses：仅本人
drop policy if exists addresses_own on public.addresses;
create policy addresses_own on public.addresses for all
  using (user_id = auth.uid()) with check (user_id = auth.uid());

-- orders：买卖双方/管理员可读；写入全部走 RPC
drop policy if exists orders_select on public.orders;
create policy orders_select on public.orders for select
  using (buyer_id = auth.uid() or seller_id = auth.uid() or public.is_admin());

revoke insert, update, delete on public.orders from anon, authenticated;

-- comments：公开读；本人可发/删；管理员可删
drop policy if exists comments_select on public.comments;
create policy comments_select on public.comments for select using (true);

drop policy if exists comments_insert_own on public.comments;
create policy comments_insert_own on public.comments for insert
  with check (commenter_id = auth.uid());

drop policy if exists comments_delete_own on public.comments;
create policy comments_delete_own on public.comments for delete
  using (commenter_id = auth.uid() or public.is_admin());

-- interactions：计数需要公开读；本人可增删
drop policy if exists interactions_select on public.interactions;
create policy interactions_select on public.interactions for select using (true);

drop policy if exists interactions_insert_own on public.interactions;
create policy interactions_insert_own on public.interactions for insert
  with check (user_id = auth.uid());

drop policy if exists interactions_delete_own on public.interactions;
create policy interactions_delete_own on public.interactions for delete
  using (user_id = auth.uid());

-- messages：仅收发双方可读；只能以本人身份发送；接收方可标记已读
drop policy if exists messages_select on public.messages;
create policy messages_select on public.messages for select
  using (sender_id = auth.uid() or receiver_id = auth.uid());

drop policy if exists messages_insert_own on public.messages;
create policy messages_insert_own on public.messages for insert
  with check (sender_id = auth.uid());

drop policy if exists messages_update_read on public.messages;
create policy messages_update_read on public.messages for update
  using (receiver_id = auth.uid()) with check (receiver_id = auth.uid());

-- 接收方只能改已读状态，不能改消息内容
revoke update on public.messages from anon, authenticated;
grant update (is_read) on public.messages to authenticated;

-- notifications：仅本人
drop policy if exists notifications_own on public.notifications;
create policy notifications_own on public.notifications for all
  using (receiver_id = auth.uid()) with check (receiver_id = auth.uid());

-- announcements：公开读，管理员写
drop policy if exists announcements_select on public.announcements;
create policy announcements_select on public.announcements for select using (true);

drop policy if exists announcements_admin_write on public.announcements;
create policy announcements_admin_write on public.announcements for all
  using (public.is_admin()) with check (public.is_admin());

