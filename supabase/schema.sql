$$;

-- 取消订单
create or replace function public.cancel_order(p_order_id bigint)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid uuid := auth.uid();
  v_order public.orders;
  v_other uuid;
begin
  select * into v_order from public.orders where id = p_order_id for update;
  if not found then raise exception '订单不存在'; end if;
  if v_order.buyer_id <> v_uid and v_order.seller_id <> v_uid then
    raise exception '无权操作';
  end if;
  if v_order.status > 2 then raise exception '订单状态异常'; end if;

  update public.orders set status = 4, cancel_time = now() where id = p_order_id;
  update public.products set status = 1 where id = v_order.product_id;

  v_other := case when v_order.buyer_id = v_uid then v_order.seller_id else v_order.buyer_id end;
  insert into public.notifications (receiver_id, title, content)
  values (v_other, '订单已取消', '订单 ' || v_order.order_no || ' 已被取消。');
end;
$$;

-- 商品评论（含评论人 / 被回复人昵称）
create or replace function public.get_product_comments(p_product_id bigint)
returns table (
  id bigint, content text, comment_time timestamptz, parent_id bigint,
  commenter_id uuid, commenter_nickname text, commenter_avatar text,
  replier_nickname text
)
language sql
stable
security definer
set search_path = public
as $$
  select c.id, c.content, c.comment_time, c.parent_id, c.commenter_id,
         u.nickname as commenter_nickname, u.avatar as commenter_avatar,
         r.nickname as replier_nickname
  from public.comments c
  join public.profiles u on u.id = c.commenter_id
  left join public.profiles r on r.id = c.replier_id
  where c.product_id = p_product_id
  order by c.comment_time desc;
$$;

-- 最近会话列表
create or replace function public.get_recent_chats()
returns table (
  id bigint, sender_id uuid, receiver_id uuid, content text,
  send_time timestamptz, is_read smallint,
  other_nickname text, other_avatar text, other_id uuid, unread_count bigint
)
language sql
stable
security definer
set search_path = public
as $$
  with v as (
    select auth.uid() as uid
  ),
  pairs as (
    select
      case when m.sender_id = v.uid then m.receiver_id else m.sender_id end as other_id,
      max(m.id) as max_id
    from public.messages m, v
    where (m.sender_id = v.uid or m.receiver_id = v.uid)
      and m.sender_id <> m.receiver_id
    group by 1
  )
  select m.id, m.sender_id, m.receiver_id, m.content, m.send_time, m.is_read,
         p.nickname as other_nickname, p.avatar as other_avatar,
         pairs.other_id,
         (select count(*) from public.messages x
          where x.sender_id = pairs.other_id
            and x.receiver_id = v.uid
            and x.is_read = 0) as unread_count
  from pairs
  join public.messages m on m.id = pairs.max_id
  join public.profiles p on p.id = pairs.other_id
  cross join v
  order by m.send_time desc;
$$;

