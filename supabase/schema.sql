create extension if not exists pgcrypto;

-- ------------------------------------------------------------
-- 1. 表结构
-- ------------------------------------------------------------

create table if not exists public.profiles (
  id           uuid primary key references auth.users (id) on delete cascade,
  username     text not null,
  nickname     text not null,
  avatar       text,
  phone        text,
  email        text,
  role         smallint not null default 0 check (role in (0, 1)),
  status       smallint not null default 1 check (status in (0, 1)),
  register_time timestamptz not null default now()
);
create unique index if not exists profiles_username_lower_idx
  on public.profiles (lower(username));

create table if not exists public.categories (
  id            bigint generated by default as identity primary key,
  category_name text not null,
  product_count integer not null default 0
);

create table if not exists public.products (
  id             bigint generated by default as identity primary key,
  user_id        uuid not null references public.profiles (id) on delete cascade,
  product_name   text not null,
  product_image  text,
  publish_time   timestamptz not null default now(),
  price          numeric(10, 2) not null default 0,
  description    text,
  category_id    bigint references public.categories (id) on delete set null,
  item_condition text,
  status         smallint not null default 1 check (status in (0, 1, 2, 3)),
  version        integer not null default 0,
  view_count     integer not null default 0
);
create index if not exists products_user_id_idx on public.products (user_id);
create index if not exists products_category_id_idx on public.products (category_id);
create index if not exists products_status_publish_idx on public.products (status, publish_time desc);

create table if not exists public.addresses (
  id         bigint generated by default as identity primary key,
  user_id    uuid not null references public.profiles (id) on delete cascade,
  consignee  text not null,
  phone      text not null,
  address    text not null,
  is_default smallint not null default 0 check (is_default in (0, 1))
);
create index if not exists addresses_user_id_idx on public.addresses (user_id);

create table if not exists public.orders (
  id              bigint generated by default as identity primary key,
  order_no        text not null unique,
  buyer_id        uuid not null references public.profiles (id),
  seller_id       uuid not null references public.profiles (id),
  product_id      bigint not null references public.products (id),
  deal_price      numeric(10, 2) not null default 0,
  status          smallint not null default 0 check (status in (0, 1, 2, 3, 4)),
  address_id      bigint references public.addresses (id) on delete set null,
  remark          text,
  delivery_method text default '面交',
  create_time     timestamptz not null default now(),
  pay_time        timestamptz,
  ship_time       timestamptz,
  confirm_time    timestamptz,
  cancel_time     timestamptz
);
create index if not exists orders_buyer_id_idx on public.orders (buyer_id, create_time desc);
create index if not exists orders_seller_id_idx on public.orders (seller_id, create_time desc);
create index if not exists orders_product_id_idx on public.orders (product_id);
create index if not exists orders_status_idx on public.orders (status);

create table if not exists public.comments (
  id           bigint generated by default as identity primary key,
  product_id   bigint not null references public.products (id) on delete cascade,
  parent_id    bigint references public.comments (id) on delete cascade,
  commenter_id uuid not null references public.profiles (id) on delete cascade,
  replier_id   uuid references public.profiles (id) on delete set null,
  content      text not null,
  comment_time timestamptz not null default now()
);
create index if not exists comments_product_id_idx on public.comments (product_id, comment_time desc);

create table if not exists public.interactions (
  id          bigint generated by default as identity primary key,
  user_id     uuid not null references public.profiles (id) on delete cascade,
  product_id  bigint not null references public.products (id) on delete cascade,
  type        text not null check (type in ('like', 'favorite', 'want')),
  create_time timestamptz not null default now(),
  unique (user_id, product_id, type)
);
create index if not exists interactions_product_id_idx on public.interactions (product_id);

create table if not exists public.messages (
  id          bigint generated by default as identity primary key,
  sender_id   uuid not null references public.profiles (id) on delete cascade,
  receiver_id uuid not null references public.profiles (id) on delete cascade,
  content     text not null,
  send_time   timestamptz not null default now(),
  is_read     smallint not null default 0 check (is_read in (0, 1))
);
create index if not exists messages_pair_idx on public.messages (sender_id, receiver_id, send_time);
create index if not exists messages_receiver_idx on public.messages (receiver_id, is_read);

create table if not exists public.notifications (
  id          bigint generated by default as identity primary key,
  receiver_id uuid not null references public.profiles (id) on delete cascade,
  title       text not null,
  content     text,
  is_read     smallint not null default 0 check (is_read in (0, 1)),
  create_time timestamptz not null default now()
);
create index if not exists notifications_receiver_idx on public.notifications (receiver_id, create_time desc);

create table if not exists public.announcements (
  id           bigint generated by default as identity primary key,
  publisher_id uuid references public.profiles (id) on delete set null,
  title        text not null,
  content      text,
  status       smallint not null default 0 check (status in (0, 1)),
  publish_time timestamptz not null default now()
);

-- 基础授权（Supabase 默认也会授权；这里显式写一遍，避免项目默认权限不同）
grant usage on schema public to anon, authenticated;
grant select on all tables in schema public to anon, authenticated;
grant insert, update, delete on all tables in schema public to authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;

-- 私信实时推送（Realtime）。重复添加时忽略。
do $$
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime') then
    begin
      alter publication supabase_realtime add table public.messages;
    exception
      when duplicate_object then null;
    end;
  end if;
end $$;

-- ------------------------------------------------------------
-- 2. 新用户触发器：注册时自动建 profiles
-- ------------------------------------------------------------

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, username, nickname, avatar, phone, email, role, status)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'username', split_part(new.email, '@', 1)),
    coalesce(new.raw_user_meta_data ->> 'nickname', split_part(new.email, '@', 1)),
    null,
    new.raw_user_meta_data ->> 'phone',
    new.raw_user_meta_data ->> 'email',
    0,
    1
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

