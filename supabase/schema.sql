create or replace function public.admin_active_users()
returns table ("userId" uuid, nickname text, avatar text, "publishCount" bigint)
language plpgsql
stable
security definer
set search_path = public
as $$
begin
  if not public.is_admin() then raise exception '无权操作'; end if;
  return query
    with stats as (
      select p.id, p.nickname, p.avatar, count(pr.id)::bigint as publish_count
      from public.profiles p
      left join public.products pr on pr.user_id = p.id
      where p.role = 0
      group by p.id, p.nickname, p.avatar
