-- 分类统计
create or replace function public.category_stats()
returns table (
  "categoryId" bigint, "categoryName" text,
  "productCount" bigint, "soldCount" bigint,
  "avgPrice" numeric, "totalPrice" numeric
)
language sql
stable
security definer
set search_path = public
as $$
  select c.id, c.category_name,
         count(p.id) filter (where p.status = 1)::bigint,
         count(p.id) filter (where p.status = 2)::bigint,
