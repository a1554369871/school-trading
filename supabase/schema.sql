create or replace function public.admin_create_announcement(p_title text, p_content text, p_status int)
returns public.announcements
language plpgsql
security definer
set search_path = public
as $$
declare
  v_ann public.announcements;
begin
  if not public.is_admin() then raise exception '无权操作'; end if;

  insert into public.announcements (publisher_id, title, content, status, publish_time)
  values (auth.uid(), p_title, p_content, p_status, now())
  returning * into v_ann;

  if p_status = 1 then
    insert into public.notifications (receiver_id, title, content)
    select p.id, '系统公告', '管理员发布了新公告：' || p_title
    from public.profiles p
    where p.status = 1;
  end if;

  return v_ann;
end;
$$;

create or replace function public.admin_delete_announcement(p_id bigint)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_title text;
begin
  if not public.is_admin() then raise exception '无权操作'; end if;
  select title into v_title from public.announcements where id = p_id;
  if not found then return; end if;
  delete from public.announcements where id = p_id;
  delete from public.notifications
  where content like '%管理员发布了新公告：' || v_title || '%';
end;
$$;

