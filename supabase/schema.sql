-- 点赞 / 收藏 / 想要：有则取消，无则添加
create or replace function public.toggle_interaction(p_product_id bigint, p_type text)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid uuid := auth.uid();
  v_exists boolean;
begin
  if v_uid is null then
    raise exception '请先登录';
  end if;
  if p_type not in ('like', 'favorite', 'want') then
    raise exception '不支持的操作类型';
  end if;

  select exists (
    select 1 from public.interactions
    where user_id = v_uid and product_id = p_product_id and type = p_type
  ) into v_exists;

  if v_exists then
    delete from public.interactions
    where user_id = v_uid and product_id = p_product_id and type = p_type;
    return false;
  else
    insert into public.interactions (user_id, product_id, type)
    values (v_uid, p_product_id, p_type);
    return true;
  end if;
end;
$$;

-- 创建订单
create or replace function public.create_order(
  p_product_id bigint,
  p_address_id bigint default null,
  p_delivery_method text default '面交',
  p_remark text default ''
)
returns public.orders
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid uuid := auth.uid();
  v_product public.products;
  v_order public.orders;
begin
  if v_uid is null then
    raise exception '请先登录';
  end if;

  select * into v_product from public.products where id = p_product_id for update;
  if not found then
    raise exception '商品不存在';
  end if;
  if v_product.user_id = v_uid then
    raise exception '不能购买自己的商品';
  end if;
  if v_product.status <> 1 then
    raise exception '商品已下架';
  end if;
  if p_delivery_method = '邮寄' and p_address_id is null then
    raise exception '请选择收货地址';
  end if;
  if p_address_id is not null and not exists (
    select 1 from public.addresses where id = p_address_id and user_id = v_uid
  ) then
    raise exception '收货地址不存在';
  end if;

  update public.products
  set status = 3, version = version + 1
  where id = p_product_id and status = 1;
  if not found then
    raise exception '商品已被其他人购买';
  end if;

  insert into public.orders (
    order_no, buyer_id, seller_id, product_id, deal_price, status,
    address_id, remark, delivery_method, create_time
  ) values (
    'ORD' || to_char(now(), 'YYYYMMDDHH24MISS')
      || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 6)),
    v_uid, v_product.user_id, p_product_id, v_product.price, 0,
    p_address_id, p_remark, coalesce(p_delivery_method, '面交'), now()
  )
  returning * into v_order;

  insert into public.notifications (receiver_id, title, content)
  values (
    v_product.user_id,
    '新订单通知',
    '您的商品【' || v_product.product_name || '】已被下单，订单号：' || v_order.order_no
  );

  return v_order;
end;
$$;

-- 支付
create or replace function public.pay_order(p_order_id bigint)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid uuid := auth.uid();
  v_order public.orders;
begin
  select * into v_order from public.orders where id = p_order_id for update;
  if not found then raise exception '订单不存在'; end if;
  if v_order.buyer_id <> v_uid then raise exception '无权操作'; end if;
  if v_order.status <> 0 then raise exception '订单状态异常'; end if;

  update public.orders set status = 1, pay_time = now() where id = p_order_id;

  insert into public.notifications (receiver_id, title, content)
  values (v_order.seller_id, '买家已支付', '订单 ' || v_order.order_no || ' 买家已完成支付，请尽快发货。');
end;
$$;

